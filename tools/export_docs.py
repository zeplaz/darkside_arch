"""SQLite / targets.json → Obsidian-compatible Markdown exporter."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping, Sequence

from ds_client.models import (
    CATEGORY_INVENTORY,
    CATEGORY_LOCATION,
    CATEGORY_STAT,
    WatchTarget,
    load_targets,
)
from ds_client.sinks import DB_FILE, init_db, list_memory_map, sync_memory_map_from_targets

DOCS_PATH = Path("docs") / "memory_map.md"


def _format_chain(module: str, offsets_json: str) -> str:
    try:
        offsets = json.loads(offsets_json)
    except json.JSONDecodeError:
        return f"{module} + ?"
    if not offsets:
        return f"{module} + ?"
    return " -> ".join([f"{module} + {offsets[0]}", *[str(o) for o in offsets[1:]]])


def _location_line(row: Mapping[str, Any]) -> str:
    label = row["label"] or row["target_id"]
    chain = _format_chain(row["module"], row["offsets_json"])
    dtype = row["data_type"] or "?"
    bitmask = row["bitmask"] or "None"
    verified = row["verified_value"] if row["verified_value"] is not None else "-"
    notes = row["region"] or row["notes"] or ""
    return (
        f"| `{label}` | `{chain}` | `{dtype}` | `{bitmask}` | `{verified}` | {notes} |"
    )


def _inventory_line(row: Mapping[str, Any]) -> str:
    label = row["label"] or row["target_id"]
    chain = _format_chain(row["module"], row["offsets_json"])
    dtype = row["data_type"] or "?"
    notes = row["notes"] or row["region"] or ""
    return f"| `{label}` | `{chain}` | `{dtype}` | {notes} |"


def _target_row(target: WatchTarget) -> dict:
    return {
        "target_id": target.id,
        "label": target.display_name,
        "category": target.category,
        "module": target.module,
        "offsets_json": json.dumps([f"0x{o:X}" for o in target.offsets]),
        "data_type": target.dtype,
        "bitmask": target.format_bitmask() if target.bitmask is not None else None,
        "verified_value": None,
        "region": target.region or None,
        "notes": target.notes or None,
    }


def render_memory_map_markdown(rows: Sequence[Mapping[str, Any]]) -> str:
    locations: list[str] = []
    inventory: list[str] = []
    misc: list[str] = []

    for row in rows:
        cat = (row.get("category") or "misc").lower()
        if cat == CATEGORY_LOCATION:
            locations.append(_location_line(row))
        elif cat in (CATEGORY_INVENTORY, CATEGORY_STAT):
            inventory.append(_inventory_line(row))
        else:
            misc.append(_inventory_line(row))

    lines = [
        "# Darksiders Warmastered (x64) - Memory Mapping Reference",
        "",
        "> Auto-generated by `python -m tools export-docs`.",
        "> Verified against the live 64-bit Steam build via differential capture.",
        "",
        "## Location Flags (Chests / Bosses)",
        "",
        "| Location Name | Module Offset | Data Type | Bitmask | Verified Value | Notes / Region |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    lines.extend(
        locations
        or [
            "| _(none yet)_ | | | | | Tag deltas or add `category: location_flag` targets |"
        ]
    )
    lines.extend(
        [
            "",
            "## Inventory & Stat Pointers",
            "",
            "| Stat / Item Name | Pointer Chain / Offsets | Data Type | Notes |",
            "| :--- | :--- | :--- | :--- |",
        ]
    )
    inv = inventory + misc
    lines.extend(
        inv or ["| _(none yet)_ | | | Add `category: inventory` or `stat` targets |"]
    )
    lines.append("")
    return "\n".join(lines)


def export_docs(
    *,
    db_path: Path = DB_FILE,
    out_path: Path = DOCS_PATH,
    sync_targets: bool = True,
) -> Path:
    _, targets = load_targets()
    conn = init_db(db_path)
    try:
        if sync_targets and targets:
            sync_memory_map_from_targets(conn, targets)
        rows: Sequence[Mapping[str, Any]] = list_memory_map(conn)
        if not rows and targets:
            rows = [_target_row(t) for t in targets]
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(render_memory_map_markdown(rows), encoding="utf-8")
        return out_path
    finally:
        conn.close()
